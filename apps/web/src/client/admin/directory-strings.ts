export const directoryStrings = () => (lang() === 'nl' ? nl : en);
export function managementError(key: unknown) {
  const t = directoryStrings();
  return typeof key === 'string' && key in t.errors
    ? t.errors[key as keyof typeof t.errors]
    : t.failed;
}
